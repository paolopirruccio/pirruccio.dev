function setLanguage(lang) {
    localStorage.setItem('preferredLanguage', lang);

    const toggleBtn = document.getElementById('lang-toggle-text');
    if (toggleBtn) {
        toggleBtn.textContent = lang === 'it' ? 'EN' : 'IT'; // Show option to switch TO
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (translations[lang][key].includes('<')) {
                el.innerHTML = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    document.documentElement.lang = lang;

    if (window.applyLetterHover) window.applyLetterHover();
}

window.applyLetterHover = function () {
    document.querySelectorAll('[data-hover-text]').forEach(el => {
        const text = el.textContent;
        el.innerHTML = ''; // Clear contents
        for (let char of text) {
            if (char === ' ') {
                el.appendChild(document.createTextNode(' '));
            } else {
                const span = document.createElement('span');
                span.className = 'hover-letter';
                span.textContent = char;
                el.appendChild(span);
            }
        }
    });
};

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('preferredLanguage') || 'en'; // Default to EN
    setLanguage(savedLang);

});
